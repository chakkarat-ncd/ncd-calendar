/** เกณฑ์ของหนึ่งวัน */
export type DayLimit = {
  /** ยอดสูงสุดที่ยังถือว่ารับได้สบาย — สีเขียว */
  green: number
  /** เพดานของวันนั้น เกินกว่านี้ถือว่าเกินเพดาน — สีแดง */
  cap: number
}

/**
 * ตารางเกณฑ์แยกตามวันในสัปดาห์ ดัชนี 0-6 ตรงกับ Date.getDay() คือ 0 = อาทิตย์
 * ยอดที่อยู่ระหว่าง green กับ cap คือใกล้เต็ม — สีเหลือง
 *
 * วันศุกร์เป็นวันคลินิก CKD ซึ่งรับได้น้อยกว่าวันอื่น จึงใช้เกณฑ์เข้มกว่า
 *
 * จะแก้เกณฑ์ของวันไหนก็แก้ที่ตารางนี้ที่เดียว ไม่ต้องแตะตรรกะที่อื่นเลย
 * ทุกแถวเป็น object ของตัวเอง แก้วันหนึ่งจึงไม่กระทบวันอื่น
 */
export const DAY_LIMITS: readonly DayLimit[] = [
  { green: 60, cap: 80 }, // 0 อาทิตย์
  { green: 60, cap: 80 }, // 1 จันทร์
  { green: 60, cap: 80 }, // 2 อังคาร
  { green: 60, cap: 80 }, // 3 พุธ
  { green: 60, cap: 80 }, // 4 พฤหัสบดี
  { green: 45, cap: 60 }, // 5 ศุกร์ — คลินิก CKD รับได้น้อยกว่าวันอื่น
  { green: 60, cap: 80 }, // 6 เสาร์
]

/**
 * เกณฑ์ของวันที่กำหนด — จุดเดียวที่ทุกส่วนของระบบใช้ค้นเกณฑ์
 * ทั้งสีในปฏิทิน ตัวเลขสรุป ตารางวันที่ยังรับได้ และ tooltip จึงตรงกันเสมอ
 */
export function limitOf(date: Date): DayLimit {
  return DAY_LIMITS[date.getDay()]
}

